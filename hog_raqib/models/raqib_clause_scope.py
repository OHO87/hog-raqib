def focus_for(code, number):
    """نص «ماذا يُفحص في المرحلة الأولى» لبند بعينه، أو نص فارغ."""
    return STAGE1_FOCUS.get((code, number)) or STAGE1_FOCUS.get(number) or ""


def scope_of(code, number):
    """أعلام النطاق الأربعة + وسم نواة المراقبة لبند بعينه."""
    key = (code, number)
    return {
        "applies_stage1": key in STAGE1_CLAUSES,
        "applies_stage2": True,
        "applies_surveillance": True,
        "applies_recert": True,
        "is_surveillance_core": key in SURVEILLANCE_CORE,
        "stage1_focus": focus_for(code, number) if key in STAGE1_CLAUSES else "",
    }


def apply_scope(env, only_missing=False):
    """تطبيق المصفوفة على بنود المواصفات الثلاث. يُستدعى من الترحيل ومن
    post_init_hook. آمن للتكرار.

    :param only_missing: لا يمس البنود التي عُدِّلت يدوياً (stage1_focus مملوء).
    :return: عدد البنود المحدّثة.
    """
    clauses = env["raqib.clause"].sudo().search([
        ("standard_id.code", "in", ["9001", "14001", "45001"]),
    ])
    updated = 0
    for clause in clauses:
        if only_missing and clause.stage1_focus:
            continue
        vals = scope_of(clause.standard_id.code, clause.number)
        if not clause.is_leaf:
            # البنود الأب لا تولّد أسطراً — نُبقيها خارج كل الأنواع لوضوح القوائم
            vals.update({"applies_stage1": False, "applies_stage2": False,
                         "applies_surveillance": False, "applies_recert": False,
                         "is_surveillance_core": False, "stage1_focus": ""})
        diff = {k: v for k, v in vals.items() if clause[k] != v}
        if diff:
            clause.write(diff)
            updated += 1
    return updated
